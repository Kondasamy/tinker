/**
 * Who labels the data (KTD5): writes data/labelling/labels.json, three stand-in labellers' intents for every ticket in
 * data/labelling/tickets.json, from seeded profiles. Run once by hand (`node scripts/make-labels.mjs`), reviewed and
 * frozen; tests/unit/labelling-engine.test.ts reruns makeLabels() and compares it with the file.
 *
 * Each labeller slips on a ticket at their own rate, more often on a ticket with a plausible misreading (its `decoy`),
 * and a slip mostly lands on that misreading. Mira also reads refund and return as one intent until chapter 3's
 * guideline, picking either at random; `guided` holds her labels after it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SEED = 20261030;

/** slip: the chance of a wrong label on a plain ticket (easy) and on one with a decoy (hard) */
export const PROFILES = [
  { id: 'rosa', name: 'Rosa', look: 'rosa', kind: 'careful', slip: { easy: 0.02, hard: 0.12 } },
  { id: 'mira', name: 'Mira', look: 'mira', kind: 'merges refund and return', slip: { easy: 0.03, hard: 0.15 } },
  { id: 'tom', name: 'Tom', look: 'tom', kind: 'rushed', slip: { easy: 0.25, hard: 0.45 } },
];
const MERGED = ['refund', 'return'];

/** mulberry32, as src/lib/recall.ts's shuffle uses */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Every labeller's label for each ticket, in ticket order.
 * @param {{ intents: { id: string }[]; tickets: { intent: string; decoy?: string }[] }} data
 */
export function makeLabels(data, seed = SEED) {
  const ids = data.intents.map(i => i.id);
  const labels = {},
    guided = {};
  PROFILES.forEach((p, k) => {
    const r = rng(seed + k);
    const mine = data.tickets.map(t => {
      // three draws per ticket whatever happens, so one ticket's outcome never shifts another's
      const slip = r(),
        which = r(),
        coin = r();
      if (slip >= (t.decoy ? p.slip.hard : p.slip.easy)) return { label: t.intent, coin };
      if (t.decoy && which < 0.8) return { label: t.decoy, coin };
      const others = ids.filter(i => i !== t.intent && i !== t.decoy);
      return { label: others[Math.floor(which * others.length) % others.length], coin };
    });
    if (p.id === 'mira') {
      guided.mira = mine.map(m => m.label);
      labels.mira = data.tickets.map((t, i) =>
        MERGED.includes(t.intent) ? MERGED[mine[i].coin < 0.5 ? 0 : 1] : mine[i].label,
      );
    } else labels[p.id] = mine.map(m => m.label);
  });
  return {
    note: 'Stand-in labels, not real people’s work: generated by scripts/make-labels.mjs from the seeded profiles below. labels are before chapter 3’s guideline; guided holds the labels that change after it.',
    seed,
    labellers: PROFILES,
    labels,
    guided,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const tickets = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/labelling/tickets.json'), 'utf8'));
  const out = path.join(ROOT, 'data/labelling/labels.json');
  fs.writeFileSync(out, `${JSON.stringify(makeLabels(tickets), null, 2)}\n`);
  console.log(`make-labels: wrote ${path.relative(ROOT, out)}`);
}
