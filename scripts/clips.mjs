/**
 * Renders every chapter's opener clip into public/video/<module>/<chapter>.{mp4,jpg,vtt}.
 * Run: pnpm clips [chapter-id …] — after changing a chapter's `intro.clip` lines or the scene its keyframes draw.
 * Builds the site with the dev pages (src/dev/clip.astro draws the keyframes with the scene code), writes one HyperFrames
 * project per clip into video/<module>/<chapter>/ (generated: edit this script or the dev page, not the project), then
 * checks and renders it with the pinned CLI and cuts the poster with ffmpeg. Needs FFmpeg and Chrome; CI never runs it,
 * the outputs are committed. Pass --no-build to reuse the last build.
 */
import { execFileSync, execSync } from 'node:child_process';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HYPERFRAMES = 'hyperframes@0.8.191';
const W = 1280,
  H = 720,
  FPS = 30,
  CRF = 30; // tuned so a 30 s clip of the paper and ink stays under 1 MB (video/README.md)
const FADE = 0.5;
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const only = args.filter(a => !a.startsWith('--'));

if (!args.includes('--no-build'))
  execSync('astro build', { cwd: ROOT, stdio: 'inherit', env: { ...process.env, DEV_PAGES: '1' } });
const page = await readFile(path.join(ROOT, 'dist/dev/clip/index.html'), 'utf8');
const clips = JSON.parse(/<script type="application\/json" id="clips">([\s\S]*?)<\/script>/.exec(page)[1]);

const words = t => t.split(/\s+/).filter(Boolean).length;
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const t3 = n => +n.toFixed(3);
/** each line holds 1.4 s plus 0.32 s a word, at least 2.8 s */
const beats = lines => {
  let at = 0.3;
  return lines.map(l => {
    const d = Math.max(2.8, 1.4 + 0.32 * words(l)),
      b = { start: t3(at), end: t3(at + d) };
    at += d;
    return b;
  });
};
const vttTime = s => {
  const ms = Math.round(s * 1000),
    hh = String(Math.floor(ms / 3600000)).padStart(2, '0'),
    mm = String(Math.floor(ms / 60000) % 60).padStart(2, '0'),
    ss = String(Math.floor(ms / 1000) % 60).padStart(2, '0');
  return `${hh}:${mm}:${ss}.${String(ms % 1000).padStart(3, '0')}`;
};
const vtt = lines =>
  `WEBVTT\n\n${beats(lines)
    .map((b, i) => `${vttTime(b.start)} --> ${vttTime(b.end)}\n${lines[i]}\n`)
    .join('\n')}`;

function composition({ lines, frames }) {
  const bs = beats(lines),
    total = t3(bs.at(-1).end + 0.8);
  const keyframes = frames
    .map((svg, i) => {
      const end = i + 1 < bs.length ? bs[i + 1].start + FADE : total;
      return `      <div id="k${i}" class="clip key" data-start="${bs[i].start}" data-duration="${t3(end - bs[i].start)}" data-track-index="1" style="z-index:${i + 1}"><div class="art">${svg}</div></div>`;
    })
    .join('\n');
  const texts = lines
    .map(
      (l, i) =>
        `      <p id="l${i}" class="clip line" data-start="${bs[i].start}" data-duration="${t3(bs[i].end - bs[i].start)}" data-track-index="2"><span>${esc(l)}</span></p>`,
    )
    .join('\n');
  const tweens = bs
    .map(
      (b, i) =>
        `      tl.fromTo('#k${i} .art', { opacity: 0, y: 14 }, { opacity: 1, y: 0, duration: ${FADE}, ease: 'power2.out' }, ${b.start});\n` +
        `      tl.fromTo('#l${i} span', { opacity: 0, y: 10 }, { opacity: 1, y: 0, duration: 0.35, ease: 'power2.out' }, ${t3(b.start + 0.15)});\n` +
        `      tl.to('#l${i} span', { opacity: 0, duration: 0.25 }, ${t3(b.end - 0.3)});`,
    )
    .join('\n');
  return `<!doctype html>
<!-- generated by scripts/clips.mjs from src/dev/clip.astro: edit those, not this file -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${W}px; height: ${H}px; overflow: hidden; background: #f2efe7; }
      #paper { position: absolute; inset: 0; background: #f2efe7; }
      .key .art { position: absolute; left: 96px; top: 40px; width: 1088px; height: 540px; background: #f2efe7; }
      .key svg { width: 100% !important; height: 100% !important; }
      .line { position: absolute; left: 128px; right: 128px; top: 600px; text-align: center; z-index: 50; }
      .line span { display: inline-block; font: 700 34px/1.25 'JetBrains Mono', monospace; color: #231e16; letter-spacing: -0.01em; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="${W}" data-height="${H}">
      <div id="paper" class="clip" data-start="0" data-duration="${total}" data-track-index="0"></div>
${keyframes}
${texts}
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
${tweens}
      window.__timelines['main'] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
`;
}

const npx = (dir, ...a) => execFileSync('npx', ['--yes', HYPERFRAMES, ...a], { cwd: dir, encoding: 'utf8' });

for (const clip of clips) {
  if (only.length && !only.includes(clip.chapter)) continue;
  const name = `${clip.module}/${clip.chapter}`,
    dir = path.join(ROOT, 'video', clip.module, clip.chapter),
    out = path.join(ROOT, 'public/video', clip.module);
  await mkdir(dir, { recursive: true });
  await mkdir(out, { recursive: true });
  await writeFile(path.join(dir, 'index.html'), composition(clip));
  await writeFile(
    path.join(dir, 'hyperframes.json'),
    `${JSON.stringify({ $schema: 'https://hyperframes.heygen.com/schema/hyperframes.json', paths: { assets: 'assets' } }, null, 2)}\n`,
  );
  await writeFile(path.join(dir, 'meta.json'), `${JSON.stringify({ id: clip.chapter, name }, null, 2)}\n`);
  await writeFile(path.join(out, `${clip.chapter}.vtt`), vtt(clip.lines));

  let report;
  try {
    report = npx(dir, 'check', '--json');
  } catch (e) {
    report = e.stdout;
  }
  const errors = JSON.parse(report.slice(report.indexOf('{'))).errors ?? [];
  if (errors.length) throw new Error(`${name}: hyperframes check failed\n${JSON.stringify(errors, null, 2)}`);

  const mp4 = path.join(out, `${clip.chapter}.mp4`),
    tmp = path.join(dir, 'render.mp4');
  npx(dir, 'render', '--fps', String(FPS), '--crf', String(CRF), '--quiet', '--output', tmp);
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', tmp, '-c', 'copy', '-movflags', '+faststart', mp4]);
  await rm(tmp);
  // the poster: the whole picture, just before the last line fades
  const at = beats(clip.lines).at(-1).end - 0.4;
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-ss',
    String(at),
    '-i',
    mp4,
    '-frames:v',
    '1',
    '-q:v',
    '3',
    path.join(out, `${clip.chapter}.jpg`),
  ]);
  console.log(`clip: public/video/${name}.mp4 (${Math.round((await stat(mp4)).size / 1024)} KB)`);
}
